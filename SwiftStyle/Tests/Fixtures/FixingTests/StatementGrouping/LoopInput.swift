// MARK: - Input
enum Examples {

  static func process(_ input: [Int]) {
    let values = input

    for value in values {
      print(value)
    }
  }
}

// MARK: - Output
enum Examples {

  static func process(_ input: [Int]) {
    let values = input
    for value in values {
      print(value)
    }
  }
}
