// MARK: - Input
enum Examples {

  static func play(_ input: Int, high: Bool) {
    let volume = input

    if high {
      print(volume)
    } else {
      print(-volume)
    }
  }
}

// MARK: - Output
enum Examples {

  static func play(_ input: Int, high: Bool) {
    let volume = input
    if high {
      print(volume)
    } else {
      print(-volume)
    }
  }
}
